export type LegacyAssetKey = keyof typeof legacyAssets;

type LegacyImageState = 'loading' | 'loaded' | 'failed';

export interface LegacyImageLoadingProgress {
  readonly loaded: number;
  readonly failed: number;
  readonly total: number;
}

interface LegacyImageRecord {
  readonly image: HTMLImageElement;
  state: LegacyImageState;
}

export class LegacyImageStore {
  private readonly records = new Map<LegacyAssetKey, LegacyImageRecord>();
  private readonly onProgress?: (progress: LegacyImageLoadingProgress) => void;

  public constructor(options: { readonly onProgress?: (progress: LegacyImageLoadingProgress) => void } = {}) {
    this.onProgress = options.onProgress;
    for (const key of Object.keys(legacyAssets) as LegacyAssetKey[]) {
      const image = new Image();
      const record: LegacyImageRecord = { image, state: 'loading' };
      image.addEventListener('load', () => {
        record.state = 'loaded';
        this.emitProgress();
      });
      image.addEventListener('error', () => {
        record.state = 'failed';
        this.emitProgress();
      });
      image.src = legacyAssets[key].url;
      this.records.set(key, record);
    }

    this.emitProgress();
  }

  public getLoaded(key: LegacyAssetKey): HTMLImageElement | null {
    const record = this.records.get(key);
    return record?.state === 'loaded' ? record.image : null;
  }

  public getUrl(key: LegacyAssetKey): string {
    return legacyAssets[key].url;
  }

  public getLoadingProgress(): LegacyImageLoadingProgress {
    let loaded = 0;
    let failed = 0;

    for (const record of this.records.values()) {
      if (record.state === 'loaded') {
        loaded += 1;
      } else if (record.state === 'failed') {
        failed += 1;
      }
    }

    return {
      loaded,
      failed,
      total: this.records.size,
    };
  }

  private emitProgress(): void {
    this.onProgress?.(this.getLoadingProgress());
  }
}
